#!/usr/bin/env bash
# ──────────────────────────────────────────────────────────────────────────────
# Generate infra/helm/swiftdrop/values-secrets.yaml with strong random passwords
# and a fresh RS256 key pair (PKCS#8 private key, as auth-iam-service requires).
#
# Usage (Git Bash on Windows, or any Linux/macOS shell with openssl):
#   bash scripts/generate-helm-secrets.sh <letsencrypt-email> [admin-email]
#
# The output file is git-ignored. Back it up somewhere safe (password manager):
# the database passwords inside it are baked into the PostgreSQL volumes on first
# start, so losing the file means resetting the databases.
# ──────────────────────────────────────────────────────────────────────────────
set -euo pipefail

ACME_EMAIL="${1:-}"
ADMIN_EMAIL="${2:-${ACME_EMAIL}}"
if [ -z "$ACME_EMAIL" ]; then
  echo "usage: bash scripts/generate-helm-secrets.sh <letsencrypt-email> [admin-email]" >&2
  exit 1
fi
command -v openssl >/dev/null || { echo "openssl not found (it ships with Git for Windows)" >&2; exit 1; }

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$REPO_ROOT/infra/helm/swiftdrop/values-secrets.yaml"
if [ -e "$OUT" ]; then
  echo "Refusing to overwrite existing $OUT (delete it first if you really want new secrets)." >&2
  exit 1
fi

rand() { openssl rand -hex "${1:-24}"; }

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
openssl genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:2048 -out "$TMP/jwt-private.pem" 2>/dev/null
openssl pkey -in "$TMP/jwt-private.pem" -pubout -out "$TMP/jwt-public.pem"
indent() { sed 's/^/      /' "$1"; }

umask 077
{
  echo "# Generated by scripts/generate-helm-secrets.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). DO NOT COMMIT."
  echo "secrets:"
  echo "  postgres:"
  for db in iam order pricing dispatch delivery merchant webhook notify analytics; do
    echo "    ${db}: { username: swiftdrop, password: \"$(rand)\" }"
  done
  echo "  rabbitmq:"
  echo "    username: swiftdrop"
  echo "    password: \"$(rand)\""
  echo "    erlangCookie: \"$(rand 32)\""
  echo "  jwt:"
  echo "    secret: \"$(rand 32)\""
  echo "    privateKey: |"
  indent "$TMP/jwt-private.pem"
  echo "    publicKey: |"
  indent "$TMP/jwt-public.pem"
  echo "  bootstrapAdmin:"
  echo "    username: admin"
  echo "    password: \"$(rand 12)\""
  echo "    email: \"${ADMIN_EMAIL}\""
  echo "    district: COLOMBO"
  echo "  googleOAuth: { clientId: \"\", clientSecret: \"\" }"
  echo "  aiProvider: { apiKey: \"\" }"
  echo "certManager:"
  echo "  clusterIssuer:"
  echo "    email: \"${ACME_EMAIL}\""
} > "$OUT"

echo "Wrote $OUT"
echo "Bootstrap admin login: admin / $(grep -A2 'bootstrapAdmin:' "$OUT" | sed -n 's/.*password: "\(.*\)"/\1/p')"
echo "Next: gh secret set HELM_SECRETS_VALUES < infra/helm/swiftdrop/values-secrets.yaml"
